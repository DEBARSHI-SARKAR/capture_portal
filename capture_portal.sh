#!/usr/bin/env bash
# capture_portal — menu-driven V4L2 capture viewer using ffplay
set -uo pipefail

APP_NAME="capture_portal"
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/capture_portal"
CONFIG_FILE="$CONFIG_DIR/config"
DEFAULT_DEVICE="/dev/video0"
DEFAULT_FORMAT="mjpeg"
DEFAULT_FPS="60"

save_config() {
    mkdir -p "$CONFIG_DIR" || { echo "Warning: cannot create config directory: $CONFIG_DIR" >&2; return 1; }
    local tmp="$CONFIG_FILE.tmp.$$"
    {
        printf 'DEVICE=%q\n' "$DEVICE"
        printf 'RESOLUTION=%q\n' "$RESOLUTION"
        printf 'FPS=%q\n' "$FPS"
        printf 'INPUT_FORMAT=%q\n' "$INPUT_FORMAT"
        printf 'SYNC=%q\n' "$SYNC"
        printf 'DROP_FRAMES=%q\n' "$DROP_FRAMES"
    } > "$tmp" && mv "$tmp" "$CONFIG_FILE" || {
        rm -f "$tmp"
        echo "Warning: could not save config to $CONFIG_FILE" >&2
        return 1
    }
}

load_config() {
    # Start from defaults, then load only recognized, validated values.
    DEVICE="$DEFAULT_DEVICE"
    RESOLUTION='1920x1080'
    FPS="$DEFAULT_FPS"
    INPUT_FORMAT="$DEFAULT_FORMAT"
    SYNC='video'
    DROP_FRAMES=1

    if [[ -f "$CONFIG_FILE" ]]; then
        # This file is generated by this script; accept only known assignments.
        local key value
        while IFS='=' read -r key value; do
            value="${value%$'\r'}"
            case "$key" in
                DEVICE) [[ "$value" == /dev/video* ]] && DEVICE="$value" ;;
                RESOLUTION) [[ "$value" =~ ^[0-9]{2,5}x[0-9]{2,5}$ ]] && RESOLUTION="$value" ;;
                FPS) [[ "$value" =~ ^[0-9]{1,3}([.][0-9]+)?$ ]] && FPS="$value" ;;
                INPUT_FORMAT) [[ "$value" == mjpeg || "$value" == yuyv422 || -z "$value" ]] && INPUT_FORMAT="$value" ;;
                SYNC) [[ "$value" == video || "$value" == audio || "$value" == ext ]] && SYNC="$value" ;;
                DROP_FRAMES) [[ "$value" == 0 || "$value" == 1 ]] && DROP_FRAMES="$value" ;;
            esac
        done < "$CONFIG_FILE"
    fi
}

need_cmd() {
    command -v "$1" >/dev/null 2>&1 || {
        printf 'Missing required command: %s\n' "$1" >&2
        return 1
    }
}

pause() { read -r -p $'\nPress Enter to continue...' _; }

list_devices() {
    echo '=== Capture-card / V4L2 device detector ==='
    if command -v v4l2-ctl >/dev/null 2>&1; then
        echo '-- v4l2-ctl --list-devices --'
        v4l2-ctl --list-devices 2>&1 || true
    else
        echo 'v4l2-ctl is not installed; using /dev/video* fallback.'
        echo 'Install package: v4l-utils (package name may vary by distro).'
    fi

    echo
    shopt -s nullglob
    local devs=(/dev/video*)
    shopt -u nullglob
    if ((${#devs[@]} == 0)); then
        echo 'No /dev/video* nodes found. Is the capture card connected and detected?'
        echo 'Try: lsusb; dmesg | tail -80'
        return
    fi

    for dev in "${devs[@]}"; do
        echo
        echo "--- $dev ---"
        if command -v v4l2-ctl >/dev/null 2>&1; then
            v4l2-ctl -d "$dev" --info 2>&1 || true
            echo 'Supported formats / resolutions:'
            v4l2-ctl -d "$dev" --list-formats-ext 2>&1 || true
        else
            ls -l "$dev" 2>&1 || true
            if command -v udevadm >/dev/null 2>&1; then
                udevadm info --query=property --name="$dev" 2>/dev/null | grep -E '^(ID_VENDOR=|ID_MODEL=|ID_SERIAL=|ID_V4L_PRODUCT=|ID_BUS=)' || true
            fi
        fi
    done
}

choose_device() {
    local input
    echo 'Detected video devices:'
    shopt -s nullglob
    local devs=(/dev/video*)
    shopt -u nullglob
    if ((${#devs[@]})); then printf '  %s\n' "${devs[@]}"; else echo '  (none found)'; fi
    echo
    read -r -p "Device path [$DEFAULT_DEVICE]: " input
    DEVICE="${input:-$DEFAULT_DEVICE}"
    if [[ ! -e "$DEVICE" ]]; then
        echo "Warning: $DEVICE does not exist. Check the capture card/device path."
        return 1
    fi
    return 0
}

choose_resolution() {
    echo
    echo 'Choose resolution:'
    echo '  1) 1920x1080 (Full HD)'
    echo '  2) 1600x900'
    echo '  3) 1280x720 (HD)'
    echo '  4) 1024x768'
    echo '  5) 800x600'
    echo '  6) 640x480'
    echo '  7) Enter custom resolution'
    echo '  8) Show resolutions supported by the selected device'
    read -r -p 'Selection [1]: ' choice
    case "${choice:-1}" in
        1) RESOLUTION='1920x1080' ;;
        2) RESOLUTION='1600x900' ;;
        3) RESOLUTION='1280x720' ;;
        4) RESOLUTION='1024x768' ;;
        5) RESOLUTION='800x600' ;;
        6) RESOLUTION='640x480' ;;
        7)
            read -r -p 'Enter resolution (e.g. 1920x1080): ' RESOLUTION
            if [[ ! "$RESOLUTION" =~ ^[0-9]{2,5}x[0-9]{2,5}$ ]]; then
                echo 'Invalid resolution format.'; return 1
            fi
            ;;
        8)
            if command -v v4l2-ctl >/dev/null 2>&1; then
                v4l2-ctl -d "$DEVICE" --list-formats-ext 2>&1 || true
            else
                echo 'Install v4l-utils to list supported modes.'
            fi
            pause
            choose_resolution
            return $?
            ;;
        *) echo 'Invalid selection.'; return 1 ;;
    esac
}

choose_fps() {
    echo
    echo 'Choose capture frame rate:'
    echo '  1) 60 FPS'
    echo '  2) 30 FPS'
    echo '  3) 25 FPS'
    echo '  4) 24 FPS'
    echo '  5) 15 FPS'
    echo '  6) Custom'
    read -r -p 'Selection [1]: ' choice
    case "${choice:-1}" in
        1) FPS=60 ;; 2) FPS=30 ;; 3) FPS=25 ;; 4) FPS=24 ;; 5) FPS=15 ;;
        6)
            read -r -p 'Enter FPS: ' FPS
            if [[ ! "$FPS" =~ ^[0-9]{1,3}([.][0-9]+)?$ ]]; then echo 'Invalid FPS.'; return 1; fi
            ;;
        *) echo 'Invalid selection.'; return 1 ;;
    esac
}

choose_format() {
    echo
    echo 'Choose input format:'
    echo '  1) MJPEG (recommended for many USB capture cards)'
    echo '  2) YUYV422'
    echo '  3) Let FFmpeg choose (omit input_format)'
    read -r -p 'Selection [1]: ' choice
    case "${choice:-1}" in
        1) INPUT_FORMAT='mjpeg' ;; 2) INPUT_FORMAT='yuyv422' ;; 3) INPUT_FORMAT='' ;;
        *) echo 'Invalid selection.'; return 1 ;;
    esac
}

choose_sync() {
    echo
    echo 'Choose playback sync / frame-drop behavior:'
    echo '  1) Video clock + allow frame drops (recommended for low-latency preview)'
    echo '  2) Audio clock + allow frame drops (usually not useful without audio)'
    echo '  3) External clock + allow frame drops'
    echo '  4) Video clock + do not intentionally drop frames'
    read -r -p 'Selection [1]: ' choice
    case "${choice:-1}" in
        1) SYNC='video'; DROP_FRAMES=1 ;;
        2) SYNC='audio'; DROP_FRAMES=1 ;;
        3) SYNC='ext'; DROP_FRAMES=1 ;;
        4) SYNC='video'; DROP_FRAMES=0 ;;
        *) echo 'Invalid selection.'; return 1 ;;
    esac
}

start_preview() {
    local args=(-f v4l2 -framerate "$FPS" -video_size "$RESOLUTION")
    [[ -n "$INPUT_FORMAT" ]] && args+=(-input_format "$INPUT_FORMAT")
    args+=(-i "$DEVICE" -sync "$SYNC")
    if (( DROP_FRAMES )); then args+=(-framedrop); else args+=(-noframedrop); fi
    # This is playback synchronization, not a guaranteed hardware/display V-Sync switch.
    echo
    echo "Starting $APP_NAME: $DEVICE | $RESOLUTION | ${FPS} FPS | format=${INPUT_FORMAT:-auto} | sync=$SYNC"
    echo 'Close the ffplay window or press q to return to the menu.'
    ffplay "${args[@]}"
    local rc=$?
    if (( rc != 0 )); then
        echo
        echo "ffplay exited with status $rc. The capture card may not support this format/resolution/FPS combination."
        echo 'Use the device detector to inspect supported modes.'
        pause
    fi
}

main() {
    need_cmd ffplay || { echo 'Install FFmpeg (ffplay is usually included in the ffmpeg package).'; exit 1; }
    load_config
    [[ -f "$CONFIG_FILE" ]] || save_config

    while true; do
        clear 2>/dev/null || true
        echo '========================================'
        echo '           capture_portal'
        echo '   multiconfig portal script'
        echo '========================================'
        echo "Device:     $DEVICE"
        echo "Resolution: $RESOLUTION"
        echo "FPS:        $FPS"
        echo "Format:     ${INPUT_FORMAT:-auto}"
        echo "Sync:       $SYNC | frame dropping: $([[ $DROP_FRAMES == 1 ]] && echo on || echo off)"
        echo "Config:     $CONFIG_FILE"
        echo
        echo '  1) Start portal'
        echo '  2) Detect capture cards / list supported modes'
        echo '  3) Select video device'
        echo '  4) Select resolution'
        echo '  5) Select frame rate'
        echo '  6) Select input format'
        echo '  7) Select sync / frame-drop mode'
        echo '  8) Exit'
        read -r -p 'Choose an option: ' choice
        case "$choice" in
            1) start_preview ;;
            2) list_devices; pause ;;
            3) if choose_device; then save_config; else pause; fi ;;
            4) if choose_resolution; then save_config; else pause; fi ;;
            5) if choose_fps; then save_config; else pause; fi ;;
            6) if choose_format; then save_config; else pause; fi ;;
            7) if choose_sync; then save_config; else pause; fi ;;
            8|q|Q) exit 0 ;;
            *) echo 'Invalid option.'; pause ;;
        esac
    done
}

main "$@"
